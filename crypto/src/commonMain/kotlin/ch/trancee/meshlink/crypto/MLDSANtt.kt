  // ------------------------------------------------------------------
  // Reduction (FIPS 204 Algorithm 43–44, Dilithium ref/reduce.c)
  // ------------------------------------------------------------------

  /**
   * Montgomery reduction: for `a` in [-2^31·Q, Q·2^31], returns `r ≡ a·R⁻¹ (mod Q)` where R = 2^32,
   * such that -Q < r < Q.
   *
   * Implementation matches Dilithium ref/reduce.c `montgomery_reduce` exactly:
   * ```
   * t = (a & 0xFFFFFFFF) * QINV          // lower 32 bits × Q⁻¹ mod 2³²
   * r = (a - t·Q) >> 32                   // exact division by R = 2³²
   * ```
   *
   * The Kotlin `Long` type provides 64-bit signed two's-complement arithmetic, matching the C
   * `int64_t` behavior.
   */
  internal fun montgomeryReduce(a: Long): Int {
    val t = a.toInt() * QINV
    val r = (a - t.toLong() * Q) shr 32
    return r.toInt()
  }

  /**
   * Barrett-like reduction (FIPS 204 Algorithm 44): for `a` with |a| < 2^31 - 2^22 - 1, returns `r
   * ≡ a (mod Q)` with -6283008 ≤ r ≤ 6283008.
   *
   * This is a *lazy* reduction — the bound 6283008 = (3/4)·Q allows several add/subtract operations
   * before re-reduction is needed, avoiding per-step modular reduction in the NTT butterfly.
   */
  internal fun reduce32(a: Int): Int {
    val t = (a + (1 shl 22)) shr 23
    return a - t * Q
  }

  /**
   * Conditionally adds Q if [a] is negative (branch-free).
   *
   * Uses `a ushr 31` to produce a mask: 0xFFFFFFFF if a < 0, 0x00000000 otherwise. The `&` with Q
   * selects Q (when a < 0) or 0 (when a ≥ 0).
   */
  internal fun caddq(a: Int): Int {
    return a + ((a shr 31) and Q)
  }

  /**
   * Full reduction to the standard representative r = a mod⁺ Q, i.e., r ∈ [0, Q).
   *
   * Combines [reduce32] (lazy reduction to [-3Q/4, 3Q/4]) with [caddq] (shift to [0, Q)).
   */
  internal fun freeze(a: Int): Int {
    val r = reduce32(a)
    return caddq(r)
  }

  // ------------------------------------------------------------------
  // Forward NTT (FIPS 204 Algorithm 41, Dilithium ref/ntt.c `ntt`)
  // ------------------------------------------------------------------

  /**
   * In-place forward NTT (Cooley-Tukey butterfly).
   *
   * Computes the NTT of [a] using the zetas in Montgomery form. After this call, coefficients are
   * in NTT + Montgomery domain. No modular reduction is performed after additions/subtractions —
   * values may grow up to 8Q per coefficient (lazy reduction, the intermediate bounds are safe for
   * int32 arithmetic).
   *
   * @param a coefficient array of length 256; **modified in place**
   */
  internal fun ntt(@Secret a: IntArray) {
    var k = 0
    var length = 128
    while (length > 0) {
      var start = 0
      while (start < N) {
        val zeta = zetas[++k]
        var j = start
        while (j < start + length) {
          val t = montgomeryReduce(zeta.toLong() * a[j + length])
          a[j + length] = a[j] - t
          a[j] = a[j] + t
          j++
        }
        start += length shl 1
      }
      length = length shr 1
    }
  }

  // ------------------------------------------------------------------
  // Inverse NTT + Montgomery normalization (FIPS 204 Algorithm 42)
  // ------------------------------------------------------------------

  /**
   * In-place inverse NTT with Montgomery normalization (Gentleman-Sande butterfly).
   *
   * Recovers coefficients from the NTT + Montgomery domain back to the standard representation.
   * After this call, `result[i] ≡ input[i] · MONT (mod Q)` where MONT = 2^32 mod Q, so coefficients
   * are still in Montgomery form.
   *
   * Input coefficients must be smaller than Q in absolute value. No modular reduction is performed
   * after additions/subtractions (lazy reduction).
   *
   * @param a coefficient array of length 256; **modified in place**
   */
  internal fun invnttTomont(@Secret a: IntArray) {
    var k = N
    var length = 1
    while (length < N) {
      var start = 0
      while (start < N) {
        val zeta = -zetas[--k]
        var j = start
        while (j < start + length) {
          val t = a[j]
          a[j] = t + a[j + length]
          a[j + length] = t - a[j + length]
          a[j + length] = montgomeryReduce(zeta.toLong() * a[j + length])
          j++
        }
        start += length shl 1
      }
      length = length shl 1
    }
    for (j in 0 until N) {
      a[j] = montgomeryReduce(F.toLong() * a[j])
    }
  }
}
