 * ML-DSA-44 NTT engine (FIPS 204 §4.2, Algorithms 41–44).
 *
 * Pure-Kotlin implementation of the Number-Theoretic Transform over Z_q with q = 8380417.
 * All reduction paths are branch-free on secret data (ADR-0003):
 * - montgomeryReduce uses 64-bit word arithmetic with no secret-dependent branches
 * - reduce32 uses a single arithmetic right-shift (FIPS 204 Algorithm 44)
 * - caddq uses arithmetic right-shift by 31 to produce a 0/Q mask
 * - ntt/invnttTomont use the standard CTC / GS butterfly with no conditional branches
 *
 * The zetas table stores 256 roots of unity in Montgomery form (ζ_i * 2^32 mod Q)
 * so that `montgomeryReduce(zeta * a[j+len])` computes `ζ * a[j+len] mod Q`
 * directly, eliminating a separate modular reduction per butterfly step.
 *
 * Reference: pq-crystals/dilithium ref/ntt.c, ref/reduce.c
 */
