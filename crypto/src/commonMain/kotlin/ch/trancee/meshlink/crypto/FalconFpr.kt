 * in the pure-K path, per ADR-0001.
 *
 * The `fpr` type is a raw 64-bit IEEE 754 binary64 bit-pattern stored as a
 * Kotlin [Long]. Bit-level manipulation uses [Long.ushr] for unsigned semantics
 * and arithmetic shifts where the C source relies on sign extension.
 *
 * References:
 *   - PQClean: crypto_sign/falcon-512/clean/fpr.h and fpr.c
 *   - RFC 8031 (Falcon), Appendix B.2 for the FP implementation notes
 *   - Thomas Pornin's original BearSSL fpr.h documentation
 */
